CREATE TABLE IF NOT EXISTS customer_segments (
    segment_id TEXT PRIMARY KEY,
    segment_name TEXT NOT NULL,
    source_group TEXT,
    cluster_id INTEGER,
    description TEXT,
    transaction_behavior TEXT,
    balance_and_cashflow_behavior TEXT,
    digital_channel_behavior TEXT,
    likely_customer_objectives TEXT,
    potential_risks TEXT,
    supporting_statistics TEXT,
    interpretation_confidence TEXT,
    requires_manual_review BOOLEAN NOT NULL DEFAULT false,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (source_group, cluster_id)
);

CREATE TABLE IF NOT EXISTS customer_products (
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    product_id TEXT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    product_model_segment TEXT,
    family TEXT,
    run_id BIGINT NOT NULL REFERENCES model_runs(run_id) ON DELETE CASCADE,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (customer_id, product_id, run_id)
);

ALTER TABLE customer_products
DROP COLUMN IF EXISTS owns_probability;

CREATE TABLE IF NOT EXISTS propensity_predictions (
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    product_id TEXT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    propensity_score NUMERIC(8,6) NOT NULL CHECK (propensity_score BETWEEN 0 AND 1),
    segment_product_prior NUMERIC(8,6) CHECK (segment_product_prior BETWEEN 0 AND 1),
    max_owned_to_candidate_affinity NUMERIC(8,6) CHECK (max_owned_to_candidate_affinity BETWEEN 0 AND 1),
    mean_owned_to_candidate_affinity NUMERIC(8,6) CHECK (mean_owned_to_candidate_affinity BETWEEN 0 AND 1),
    rank INTEGER CHECK (rank > 0),
    product_model_segment TEXT,
    family TEXT,
    run_id BIGINT NOT NULL REFERENCES model_runs(run_id) ON DELETE CASCADE,
    scored_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (customer_id, product_id, run_id)
);

CREATE TABLE IF NOT EXISTS recommendations (
    customer_id BIGINT NOT NULL REFERENCES customers(customer_id) ON DELETE CASCADE,
    product_id TEXT NOT NULL REFERENCES products(product_id) ON DELETE RESTRICT,
    rank INTEGER NOT NULL CHECK (rank > 0),
    score NUMERIC(8,6) NOT NULL CHECK (score BETWEEN 0 AND 1),
    reason TEXT,
    run_id BIGINT NOT NULL REFERENCES model_runs(run_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (customer_id, rank, run_id),
    UNIQUE (customer_id, product_id, run_id)
);

CREATE TABLE IF NOT EXISTS segment_forecasts (
    forecast_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool TEXT NOT NULL,
    metric TEXT NOT NULL,
    forecast_date DATE NOT NULL,
    scenario_case TEXT NOT NULL,
    model_name TEXT NOT NULL,
    actual_value NUMERIC,
    predicted_value NUMERIC NOT NULL,
    abs_error NUMERIC,
    run_id BIGINT NOT NULL REFERENCES model_runs(run_id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (pool, metric, forecast_date, scenario_case, model_name, run_id)
);

CREATE INDEX IF NOT EXISTS idx_customer_products_product ON customer_products(product_id);
CREATE INDEX IF NOT EXISTS idx_propensity_predictions_customer_rank ON propensity_predictions(customer_id, rank);
CREATE INDEX IF NOT EXISTS idx_recommendations_customer_rank ON recommendations(customer_id, rank);
CREATE INDEX IF NOT EXISTS idx_segment_forecasts_pool_metric_date ON segment_forecasts(pool, metric, forecast_date);
CREATE INDEX IF NOT EXISTS idx_customers_behavioral_segment ON customers(behavioral_segment_id);
CREATE INDEX IF NOT EXISTS idx_customers_forecast_pool ON customers(forecast_pool);
