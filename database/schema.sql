CREATE TABLE IF NOT EXISTS model_runs (
    run_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_name TEXT NOT NULL,
    model_type TEXT NOT NULL,
    source_path TEXT,
    artifact_version TEXT,
    parameters JSONB NOT NULL DEFAULT '{}'::jsonb,
    metrics JSONB NOT NULL DEFAULT '{}'::jsonb,
    started_at TIMESTAMPTZ,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    ownership_run_id BIGINT REFERENCES model_runs(run_id) ON DELETE RESTRICT,
    UNIQUE (run_name, model_type)
);

CREATE INDEX IF NOT EXISTS idx_model_runs_ownership_run ON model_runs(ownership_run_id);

CREATE TABLE IF NOT EXISTS products (
    product_id TEXT PRIMARY KEY,
    product_name TEXT NOT NULL UNIQUE,
    alias_notes TEXT,
    category TEXT,
    classification TEXT,
    product_type TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id BIGINT PRIMARY KEY,
    segment_label TEXT,
    behavioral_segment_id TEXT REFERENCES customer_segments(segment_id) ON DELETE SET NULL,
    forecast_pool TEXT,
    latent_archetype TEXT,
    customer_class TEXT,
    employment TEXT,
    income_decile INTEGER,
    tenure_days INTEGER,
    source_system TEXT NOT NULL DEFAULT 'simulated',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

